"""Generates src/features/care/careAssets.generated.ts for the mochi care screen.

Developer tool (Python 3 + Pillow + numpy); the app never runs it.

Inputs
  --thumbs <dir>   GACHA/thumb/*.webp card thumbnails (512 px, same framing as the card art).
                   The file stem is the card key, e.g. S2-04-01_mozzi_epic_016_happy.
  assets/<emotion>.png        the app's default mochi = basic/<emotion>.png card (key basic-<emotion>)
  assets/care/<key>/manifest.json + *.png
                   reviewed expression layers in normalized coordinates (0..1 of the image).

Output: per key, the alpha bounds and a 24-band silhouette profile in thousandths of the
image (x of its width, y of its height), plus the expression layers with static requires.
Cards without an entry still work: the app falls back to typical bounds and no layers.

Usage: python scripts/build-care-assets.py --thumbs "C:/.../mozzi_thumb/GACHA/thumb"
"""
import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BANDS = 24  # must match PROFILE_BANDS in src/features/care/careGeometry.ts
EMOTIONS = ['happy', 'calm', 'neutral', 'sad', 'angry']


def geometry(path: Path):
    with Image.open(path) as image:
        alpha = np.asarray(image.convert('RGBA').getchannel('A')) >= 16
    h, w = alpha.shape
    ys, xs = np.nonzero(alpha)
    if len(xs) == 0:
        raise SystemExit(f'{path}: no visible pixels')
    left, top, right, bottom = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
    height = bottom - top
    nx = lambda v: int(round(v * 1000 / w))
    ny = lambda v: int(round(v * 1000 / h))
    profile = []
    for i in range(BANDS):
        y0 = top + (i * height) // BANDS
        y1 = max(y0 + 1, top + ((i + 1) * height) // BANDS)
        cols = np.nonzero(alpha[y0:y1, left:right].any(axis=0))[0]
        profile += [nx(left + cols.min()), nx(left + cols.max() + 1)] if len(cols) else [-1, -1]
    return [round(w / h, 4), nx(left), ny(top), nx(right - left), ny(height), *profile]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--thumbs', required=True, type=Path)
    args = parser.parse_args()
    shapes = {}
    for thumb in sorted(args.thumbs.glob('*.webp')):
        shapes[thumb.stem] = geometry(thumb)
    for emotion in EMOTIONS:
        shapes[f'basic-{emotion}'] = geometry(ROOT / 'assets' / f'{emotion}.png')
    sets = {}
    for manifest_path in sorted((ROOT / 'assets' / 'care').glob('*/manifest.json')):
        manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
        key = manifest_path.parent.name
        if key not in shapes:
            raise SystemExit(f'{key}: expression layers for an image with no geometry')
        sets[key] = manifest

    lines = [
        '// Generated by scripts/build-care-assets.py. Do not edit by hand.',
        '// Keys are card image file names (GACHA/<key>.png) or basic-<emotion> for the default mochi.',
        "import type { CareShapeRow, CareExpressionSource } from './careSkin';",
        '',
        '// [aspect, x, y, width, height, ...24 x (left, right)] in thousandths of the image.',
        'export const careShapes: Record<string, CareShapeRow> = {',
    ]
    for key, row in shapes.items():
        lines.append(f"  '{key}': {json.dumps(row, separators=(',', ':'))},")
    lines += ['};', '', 'export const careExpressionSources: Record<string, CareExpressionSource> = {']
    for key, m in sets.items():
        lines.append(f"  '{key}': {{")
        mouth = m['anchors']['mouth']
        lines.append(f"    mouth: {{ x: {mouth['x']}, y: {mouth['y']}, width: {mouth['width']}, height: {mouth['height']} }},")
        lines.append('    layers: [')
        for name, layer in m['layers'].items():
            lines.append(
                f"      {{ id: '{name}', source: require('../../../assets/care/{key}/{layer['file']}'), "
                f"x: {layer['x']}, y: {layer['y']}, width: {layer['width']}, height: {layer['height']} }},")
        lines.append('    ],')
        lines.append(f"    expressions: {json.dumps(m['expressions'], separators=(', ', ': '))},")
        lines.append('  },')
    lines.append('};')
    target = ROOT / 'src' / 'features' / 'care' / 'careAssets.generated.ts'
    target.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{len(shapes)} shapes, {len(sets)} expression sets -> {target.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
