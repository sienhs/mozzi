-- Emotion search (API spec emotion-search.md, ERD "감정 검색").

-- pgvector, for diary_embedding below. Local and test images ship it (compose.yaml); RDS
-- allows it for the master user, which is the user Flyway runs as.
create extension if not exists vector;

-- One row per question, written once when the answer (or the failure) is known. Failed
-- questions are kept too: the per-minute limit counts them, so retrying a failure cannot
-- get around it.
create table emotion_search
(
    emotion_search_id  bigint generated by default as identity primary key,
    member_id          bigint       not null references member (member_id),
    -- The user's own words. Never logged (convention 5.4).
    question           varchar(200) not null,
    -- The conditions the LLM read from the question; null when it failed before that.
    interpreted_filter jsonb,
    result_type        varchar(12)  not null,
    answer             varchar(500),
    latency_ms         integer,
    created_at         timestamptz  not null
);

-- The per-minute limit and the last seven days of searches that feed the weekly context.
create index ix_emotion_search_member_created_at on emotion_search (member_id, created_at);

-- The diaries an answer was based on, in display order.
create table emotion_search_result
(
    emotion_search_id bigint  not null references emotion_search (emotion_search_id),
    diary_id          bigint  not null references diary (diary_id),
    rank_no           integer not null,
    is_featured       boolean not null,
    primary key (emotion_search_id, diary_id)
);

-- Two rows with the same rank would make the display order ambiguous.
create unique index uq_emotion_search_result_rank on emotion_search_result (emotion_search_id, rank_no);
-- The response has one big card (`featured`), so at most one row per search may claim it.
create unique index uq_emotion_search_result_featured on emotion_search_result (emotion_search_id) where is_featured;
-- Purging a diary has to find its rows here first; the primary key only helps the other way.
create index ix_emotion_search_result_diary on emotion_search_result (diary_id);

-- A table of its own rather than a diary column, so switching the embedding model rebuilds
-- these rows without touching diary.
create table diary_embedding
(
    diary_id     bigint primary key references diary (diary_id),
    -- Model and dimensions together (text-embedding-3-large@1536). A row whose value differs
    -- from the configured one is stale and gets rebuilt; vectors of two models never compare.
    model        varchar(50)  not null,
    -- SHA-256 of the embedded text, so an edit that changes nothing re-embeds nothing.
    content_hash varchar(64)  not null,
    -- 1536 stays under the 2,000-dimension limit of an HNSW index on vector. No index for
    -- now: candidates are narrowed to one member and a period before they are ranked.
    embedding    vector(1536) not null,
    created_at   timestamptz  not null,
    updated_at   timestamptz  not null
);
