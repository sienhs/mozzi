-- member_card gets its own key instead of the (member_id, card_id) composite one. A member
-- still holds one row per card: the pair keeps a unique index, which the basic mozzi grant's
-- "on conflict (member_id, card_id)" also relies on. Existing rows are numbered as the column
-- is added.
alter table member_card drop constraint member_card_pkey;
alter table member_card add column member_card_id bigint generated by default as identity;
alter table member_card add primary key (member_card_id);
create unique index uq_member_card_member_card on member_card (member_id, card_id);
