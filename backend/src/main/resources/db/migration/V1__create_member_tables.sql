-- Member domain (API spec ERD 5.1 - 5.4).
--
-- Scope is deliberately one domain. A single migration holding the whole ERD cannot be
-- reviewed, and once it has run on a shared database it cannot be edited either.
--
-- timestamptz, not timestamp: the server is fixed to Asia/Seoul but a stored instant must
-- stay unambiguous. "timestamp without time zone" silently drops the offset, which is how
-- a record written at 00:30 KST ends up looking like the previous day.

create table member
(
    member_id        bigint generated by default as identity primary key,
    email            varchar(255) not null,
    nickname         varchar(20),
    provider         varchar(20)  not null,
    -- Google's "sub". Identity hangs off this, not off the email, because a Google account
    -- can change its email address while staying the same account.
    provider_subject varchar(255) not null,
    role             varchar(20)  not null,
    -- PENDING_PROFILE -> ACTIVE -> WITHDRAWN. Drives the 403 ONBOARDING_REQUIRED guard.
    status           varchar(20)  not null,
    created_at       timestamptz  not null,
    updated_at       timestamptz  not null,
    -- deleted_at rather than an is_deleted flag: the retention batch needs to know when.
    deleted_at       timestamptz
);

comment on column member.nickname is 'null until onboarding completes';
comment on column member.deleted_at is 'withdrawal time; rows are purged by a retention batch';

-- One account per Google user. Not partial on deleted_at: a withdrawn member must not be
-- able to sign up again as a second row while the retention period is still running, which
-- is what policy 9 in the API spec is about.
create unique index uq_member_provider_subject on member (provider, provider_subject);

create table member_setting
(
    member_id        bigint primary key references member (member_id),
    reminder_enabled boolean     not null default true,
    reminder_time    time        not null default '21:00',
    timezone         varchar(40) not null default 'Asia/Seoul',
    updated_at       timestamptz not null
);

create table terms_agreement
(
    terms_agreement_id bigint generated by default as identity primary key,
    member_id          bigint      not null references member (member_id),
    -- TERMS or PRIVACY, agreed together at onboarding but stored separately so a later
    -- version bump can ask for only one of them again.
    terms_type         varchar(20) not null,
    terms_version      varchar(20) not null,
    agreed_at          timestamptz not null
);

create index ix_terms_agreement_member on terms_agreement (member_id);

create table push_device
(
    push_device_id bigint generated by default as identity primary key,
    member_id      bigint       not null references member (member_id),
    device_id      varchar(64)  not null,
    platform       varchar(10)  not null,
    token          varchar(512) not null,
    is_active      boolean      not null,
    updated_at     timestamptz  not null
);

-- The app re-registers on every launch, so the same device must overwrite rather than pile
-- up rows that would each get a copy of the "image is ready" push.
create unique index uq_push_device_member_device on push_device (member_id, device_id);
