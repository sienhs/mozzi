-- Mozzi gacha (S15P31D102-121): tickets and star shards, card draws, the collection and
-- exchanges. No seasons: every active card is in the pool. Card rows are registered by the
-- server outside migrations; only the five tier rules are seeded here.

-- Tier rules. weight is out of 100,000; the application refuses to start unless there are
-- exactly five rows summing to it. Only LEGENDARY and MYTHIC can be exchanged for shards.
create table gacha_tier
(
    tier             varchar(10) primary key,
    weight           integer not null check (weight >= 0),
    duplicate_shards integer not null check (duplicate_shards >= 0),
    exchange_cost    integer check (exchange_cost > 0)
);

insert into gacha_tier (tier, weight, duplicate_shards, exchange_cost)
values ('COMMON', 45000, 1, null),
       ('RARE', 30000, 2, null),
       ('EPIC', 17000, 5, null),
       ('LEGENDARY', 7000, 15, 200),
       ('MYTHIC', 1000, 40, 400);

create table mozzi_card
(
    card_id   bigint generated by default as identity primary key,
    code      varchar(12)  not null,
    series    varchar(20)  not null,
    name      varchar(30)  not null,
    tier      varchar(10)  not null references gacha_tier (tier),
    emotion   varchar(10)  not null,
    -- cards/{code}_{source file}_{emotion}.png, under mozzi.gacha.image-base-url.
    image_key varchar(100) not null,
    is_active boolean      not null
);

create unique index uq_mozzi_card_code on mozzi_card (code);
-- A draw picks a card within its tier, among active cards only.
create index ix_mozzi_card_tier on mozzi_card (tier) where is_active;

create table member_card
(
    member_id         bigint      not null references member (member_id),
    card_id           bigint      not null references mozzi_card (card_id),
    -- Times obtained through draws and exchanges, duplicates included.
    owned_count       integer     not null check (owned_count >= 1),
    first_acquired_at timestamptz not null,
    -- Null shows NEW in the collection.
    seen_at           timestamptz,
    primary key (member_id, card_id)
);

create index ix_member_card_member on member_card (member_id);

-- One row per draw request, whatever its count.
create table gacha_draw
(
    draw_id    bigint generated by default as identity primary key,
    member_id  bigint      not null references member (member_id),
    draw_count integer     not null check (draw_count between 1 and 10),
    created_at timestamptz not null
);

create index ix_gacha_draw_member_created_at on gacha_draw (member_id, created_at);

create table gacha_draw_result
(
    draw_id        bigint      not null references gacha_draw (draw_id),
    seq            integer     not null,
    card_id        bigint      not null references mozzi_card (card_id),
    -- The card's tier when drawn, for rate statistics.
    tier           varchar(10) not null,
    first_acquired boolean     not null,
    shards_gained  integer     not null,
    primary key (draw_id, seq)
);

create table member_wallet
(
    member_id      bigint primary key references member (member_id),
    ticket_balance integer     not null check (ticket_balance >= 0),
    shard_balance  integer     not null check (shard_balance >= 0),
    updated_at     timestamptz not null
);

create table wallet_ledger
(
    wallet_ledger_id bigint generated by default as identity primary key,
    member_id        bigint      not null references member (member_id),
    currency         varchar(10) not null,
    amount           integer     not null,
    reason           varchar(20) not null,
    ref_id           bigint,
    -- SIGNUP, LOGIN:{date}, RECORD:{date}: one grant per key.
    reward_key       varchar(40),
    created_at       timestamptz not null
);

-- A draw, its shards or an exchange is written once. Rows without ref_id are not checked.
create unique index uq_wallet_ledger_ref on wallet_ledger (member_id, currency, reason, ref_id);
-- Rewards are granted with "on conflict do nothing" against this index.
create unique index uq_wallet_ledger_reward_key on wallet_ledger (member_id, reward_key) where reward_key is not null;

-- Members who signed up before this migration get the sign-up grant now, so every member
-- has a wallet and every balance equals the sum of its ledger.
insert into member_wallet (member_id, ticket_balance, shard_balance, updated_at)
select member_id, 20, 0, now()
from member
where deleted_at is null;

insert into wallet_ledger (member_id, currency, amount, reason, ref_id, reward_key, created_at)
select member_id, 'TICKET', 20, 'SIGNUP', null, 'SIGNUP', now()
from member
where deleted_at is null;
