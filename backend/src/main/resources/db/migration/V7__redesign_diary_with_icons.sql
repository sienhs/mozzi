-- Diary redesign (S15P31D102-110): activity chips become member-made icons, the emotion is
-- picked through an emoticon, and a diary has at most one picture.
--
-- Written for empty diary tables: local and shared databases were both cleared before this
-- ran. diary.emoticon_id is added as NOT NULL without a default, so a populated diary table
-- makes this migration fail instead of inventing an emoticon for old rows.

drop table diary_activity;
drop table activity;

-- One emoticon per emotion. Rows are registered by the server outside migrations.
create table emoticon
(
    emoticon_id bigint generated by default as identity primary key,
    emotion     varchar(10)  not null,
    image_url   varchar(255) not null,
    created_at  timestamptz  not null,
    updated_at  timestamptz  not null
);

create unique index uq_emoticon_emotion on emoticon (emotion);

-- Base images a member picks when making an icon. Registered by the server.
create table icon
(
    icon_id    bigint generated by default as identity primary key,
    image_url  varchar(255) not null,
    created_at timestamptz  not null,
    updated_at timestamptz  not null
);

create table my_icon
(
    my_icon_id bigint generated by default as identity primary key,
    member_id  bigint      not null references member (member_id),
    icon_id    bigint      not null references icon (icon_id),
    name       varchar(10) not null,
    category   varchar(10) not null,
    created_at timestamptz not null,
    updated_at timestamptz not null,
    deleted_at timestamptz
);

-- The per-category list and the nine-per-category count both read live icons only.
create index ix_my_icon_member_category on my_icon (member_id, category, created_at) where deleted_at is null;

-- diary: the attempt history goes away, so the pointer to the current attempt does too.
alter table diary drop constraint fk_diary_current_image;
alter table diary drop column current_image_id;
alter table diary drop column title;
alter table diary rename column memo to content;
alter table diary alter column content type varchar(50);
alter table diary add column emoticon_id bigint not null references emoticon (emoticon_id);
-- Null until a picture is requested; a diary is no longer saved together with one.
alter table diary rename column image_status to diary_image_status;
alter table diary alter column diary_image_status drop not null;

create table diary_icon
(
    diary_id   bigint not null references diary (diary_id),
    my_icon_id bigint not null references my_icon (my_icon_id),
    primary key (diary_id, my_icon_id)
);

-- One row per diary. A retry after a failure resets the same row instead of adding one.
drop table diary_image;

create table diary_image
(
    diary_image_id bigint generated by default as identity primary key,
    diary_id       bigint       not null references diary (diary_id),
    status         varchar(12)  not null,
    -- Failures the AI server reported. At three the diary cannot ask again.
    failure_count  integer      not null default 0,
    -- No FK yet: the character table arrives with the gacha work.
    character_id   bigint       not null,
    time_of_day    varchar(10),
    -- Icon names are copied, not referenced, so a deleted icon does not erase what the
    -- picture was drawn from.
    where_name     varchar(10),
    who_name       varchar(10),
    what_name      varchar(10)  not null,
    -- Public S3 URL with a random file name.
    image_url      varchar(255),
    created_at     timestamptz  not null,
    updated_at     timestamptz  not null
);

create unique index uq_diary_image_diary on diary_image (diary_id);
