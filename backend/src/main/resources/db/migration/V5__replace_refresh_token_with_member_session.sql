-- Auth domain: one login session per member, and sign-up tickets (auth design, 2026-10-27).
--
-- Data loss, on purpose: V2's refresh_token table is dropped together with its rows, which
-- signs out every member logged in through it. No released code ever wrote to it, and
-- running the history-based table next to member_session would leave two refresh schemes
-- that disagree about which token is valid.
drop table refresh_token;

-- The member's current session. The primary key is the member id, so a member can never
-- hold two sessions: a new Google login deletes the row and inserts a fresh one.
--
-- Only the SHA-256 of the current refresh token is kept. A refresh token that has already
-- been rotated away is rejected, but this table does not remember it, so reuse of an old
-- token is not detected as theft (that would need the token history RFC 9700 describes).
create table member_session
(
    member_id          bigint primary key references member (member_id),
    -- Generated on every Google login, kept across refreshes. Access tokens carry it, which
    -- is how a request made with an older session's token is turned away.
    session_id         uuid        not null,
    -- Lowercase hex SHA-256 of the whole "<sessionId>.<secret>" string, never the token.
    refresh_token_hash varchar(64) not null,
    -- Moves to "rotation time + 30 days" on every refresh.
    refresh_expires_at timestamptz not null,
    created_at         timestamptz not null,
    updated_at         timestamptz not null
);

create unique index uq_member_session_session_id on member_session (session_id);
create index ix_member_session_refresh_expires_at on member_session (refresh_expires_at);

-- Issued when Google authenticates someone who has no account yet. It carries the verified
-- Google identity across the nickname screen, so the member row is created only once the
-- nickname arrives, and it is deleted in the same transaction that creates the member.
--
-- No foreign key to member: the member does not exist yet. Expired rows hold an email
-- address, so a batch deletes them.
create table signup_ticket
(
    signup_ticket_id bigint generated by default as identity primary key,
    -- Lowercase hex SHA-256 of the ticket handed to the app.
    token_hash       varchar(64)  not null,
    provider         varchar(20)  not null,
    provider_subject varchar(255) not null,
    email            varchar(255) not null,
    expires_at       timestamptz  not null,
    created_at       timestamptz  not null,
    updated_at       timestamptz  not null
);

create unique index uq_signup_ticket_token_hash on signup_ticket (token_hash);
create index ix_signup_ticket_expires_at on signup_ticket (expires_at);
