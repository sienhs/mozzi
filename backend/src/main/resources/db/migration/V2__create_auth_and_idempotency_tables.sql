-- Cross-cutting tables that the API spec requires but its ERD does not list.
--
-- They are created now, ahead of the code that uses them (steps 4 and 6), so that the
-- schema is not edited twice: a migration that has already run on a teammate's database
-- cannot be changed, only superseded.
--
-- Both exist as tables rather than in Redis because this project decided against Redis.
-- That is fine here: neither is on a hot path, and both need to survive a restart.

-- Refresh token rotation (API spec 4.1).
--
-- Social login does not remove the need for this. The spec rotates the refresh token on
-- every use and detects reuse, which means the server has to remember which tokens it
-- issued and what replaced them.
create table refresh_token
(
    refresh_token_id bigint generated by default as identity primary key,
    member_id        bigint      not null references member (member_id),
    -- SHA-256 hex of the token, never the token itself. A dump of this table must not hand
    -- out live sessions.
    token_hash       varchar(64) not null,
    device_id        varchar(64),
    issued_at        timestamptz not null,
    expires_at       timestamptz not null,
    -- Set when this token is exchanged. A token that is presented again after this time is
    -- either a replay or the mobile app firing several refreshes at once, which is why the
    -- grace window compares against this instead of deleting the row.
    rotated_at       timestamptz,
    replaced_by_hash varchar(64),
    revoked_at       timestamptz
);

create unique index uq_refresh_token_hash on refresh_token (token_hash);
create index ix_refresh_token_member on refresh_token (member_id);
-- Lets the cleanup batch find expired rows without scanning the table.
create index ix_refresh_token_expires_at on refresh_token (expires_at);

-- Idempotency-Key handling (API spec 1, 4.4, 4.5, 4.8).
--
-- The spec defines 409 IDEMPOTENCY_CONFLICT for "same key, different body", so the request
-- body hash has to be stored, and the first response has to be replayable.
create table idempotency_record
(
    idempotency_record_id bigint generated by default as identity primary key,
    -- Scoped per member: keyed on the header alone, one client could collide with another
    -- member's in-flight request.
    member_id             bigint       not null references member (member_id),
    endpoint              varchar(100) not null,
    idempotency_key       varchar(64)  not null,
    -- SHA-256 hex of the canonical request body.
    request_hash          varchar(64)  not null,
    -- IN_PROGRESS while the first request runs, COMPLETED once a response is stored.
    -- Without this state a double tap runs the handler twice before either one finishes.
    status                varchar(12)  not null,
    response_status       integer,
    response_body         text,
    created_at            timestamptz  not null,
    completed_at          timestamptz,
    expires_at            timestamptz  not null
);

create unique index uq_idempotency_record_scope
    on idempotency_record (member_id, endpoint, idempotency_key);
create index ix_idempotency_record_expires_at on idempotency_record (expires_at);
