-- Diary domain (API spec 4.4, ERD 5.5 - 5.7).

-- Activity chips (spec 2.2). A table rather than only an enum so the hidden "manage
-- activity tags" menu (v2 wireframe M-01) can be opened later without a schema change.
create table activity
(
    activity_id bigint generated by default as identity primary key,
    code        varchar(20) not null,
    label       varchar(20) not null,
    sort_order  integer     not null,
    is_active   boolean     not null default true
);

create unique index uq_activity_code on activity (code);

