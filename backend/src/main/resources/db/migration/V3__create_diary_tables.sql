create table diary
(
    diary_id         bigint generated by default as identity primary key,
    member_id        bigint       not null references member (member_id),
    -- The "day" the record belongs to, which is not always the date of created_at: a
    -- record saved at 01:00 inside the grace window belongs to the previous day.
    record_date      date         not null,
    emotion          varchar(10)  not null,
    memo             varchar(100),
    -- Filled by the image worker together with the picture.
    title            varchar(30),
    -- The image attempt the diary currently shows. The FK is added below, after
    -- diary_image exists, because the two tables point at each other.
    current_image_id bigint,
    -- Copy of the current attempt's status so home and calendar need no join.
    image_status     varchar(12)  not null,
    created_at       timestamptz  not null,
    updated_at       timestamptz  not null,
    deleted_at       timestamptz
);

-- One diary per member per day, ignoring soft-deleted rows so a day can be written again
-- after a delete (policy 6). This replaces the ERD's MySQL active_key generated column.
--
-- It also serves the ERD's (member_id, record_date desc) index: every diary query filters
-- on deleted_at is null, and PostgreSQL scans a btree backwards for the descending order.
create unique index uq_diary_member_record_date on diary (member_id, record_date) where deleted_at is null;

-- Emotion search (spec 4.7) and the ?emotion= filter on GET /diaries.
create index ix_diary_member_emotion_record_date on diary (member_id, emotion, record_date);

create table diary_activity
(
    diary_id    bigint not null references diary (diary_id),
    activity_id bigint not null references activity (activity_id),
    primary key (diary_id, activity_id)
);

-- "Find diaries by activity" (?activity=); the primary key only helps the other direction.
create index ix_diary_activity_activity on diary_activity (activity_id, diary_id);

-- One row per generation attempt (spec 4.5). Retries add rows instead of overwriting, so
-- failures stay visible for debugging and retry limits can be counted.
create table diary_image
(
    diary_image_id bigint generated by default as identity primary key,
    diary_id       bigint       not null references diary (diary_id),
    attempt_no     integer      not null,
    status         varchar(12)  not null,
    stage          varchar(12),
    trigger_type   varchar(12)  not null,
    -- Contains diary text. Stored for quality work, never logged (convention 5.4).
    prompt         text,
    model          varchar(50),
    -- Private S3 key. The URL is presigned per request, so none is stored.
    image_key      varchar(255),
    failure_code   varchar(30),
    requested_at   timestamptz  not null,
    started_at     timestamptz,
    completed_at   timestamptz
);

-- Unique rather than the ERD's plain index: two attempts with the same number would make
-- "the latest attempt" ambiguous.
create unique index uq_diary_image_attempt on diary_image (diary_id, attempt_no);
-- Lets a watchdog find attempts stuck in PENDING or GENERATING.
create index ix_diary_image_status_requested_at on diary_image (status, requested_at);

alter table diary
    add constraint fk_diary_current_image foreign key (current_image_id) references diary_image (diary_image_id);
